#!/usr/bin/env python3
"""Write the factory presets as MPC preset files (.xpl) for the plugin folder's Presets/.

The stock MPC instruments (Mini D, Hype, Odyssey ...) ship their factory presets as one flat Presets/ folder inside
the plugin folder, named "NNNN-Category-Name.xpl": the number orders them, and the MPC's preset browser shows the
category as a folder (its back arrow leads up to the list of categories). A file without a category ("0000-Init.xpl")
sits at the top. User presets are separate: the MPC saves them wherever the user picks.

The format is copied from a preset the MPC saved itself (MPC OS 3.10.1,
2026-11-12): <pluginstate> with the plugin's description and a <state> holding a VST2 chunk set ("CcnK"/"FBCh", uid,
version, program count, 128 zero bytes, then the chunk) in JUCE's base64 variant. The chunk is the engine's own
"key=value" state text with a trailing NUL, generated by tools/preset_states.cpp exactly as the plugin would save it.

    python3 vst/make_xpl.py --values > VALUES          # presets.json as the numbers set_param() gets
    build/val/preset_states < VALUES > STATES            # tools/preset_states.cpp: each preset's exact engine state
    python3 vst/make_xpl.py STATES OUT [--so PATH] [--only N,N,...]
      STATES  output of tools/preset_states.cpp
      OUT     folder to write (vst/package_mpc.py ships vst/build/presets_xpl/ as the plugin's Presets/)
      --so    the plugin binary's path on the device, as the MPC records it (default: the SD card install)
      --only  write only these preset indices (for a trial)
"""
import argparse
import datetime
import json
import os
import re
import struct
import sys
from xml.sax.saxutils import escape, quoteattr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.environ.get("MPC_VST", os.path.expanduser("~/mpc-vst-plugins")), "tools"))
from xpl import b64enc  # noqa: E402  (the port kit's JUCE base64 writer)

DEFAULT_SO = "/media/MPC Key 37/VST2 Plugins/glaser - VST - Millstone/VST/millstone-arm64.so"
ILLEGAL = '"#@,;:<>*^|?\\/'
# Category names: presets.json categories, made safe for a file name and for the "-" split ("Riser/FX" has a slash).
CATEGORY = {"Riser/FX": "Riser & FX"}


def chunk_set(uid, version, num_programs, chunk):
    return (b"CcnK" + struct.pack(">i", 0) + b"FBCh" + struct.pack(">iiii", 1, uid, version, num_programs)
            + bytes(128) + struct.pack(">i", len(chunk)) + chunk)


def xpl_text(cfg, so, preset_name, state):
    uid = int.from_bytes(cfg["uid"].encode(), "big")
    blob = chunk_set(uid, cfg["version"], cfg["nprograms"], state.encode() + b"\0")
    date = datetime.datetime.now().strftime("%Y-%m-%d-%H-%M")
    return ('<?xml version="1.0" encoding="UTF-8"?>\n\n<pluginstate>\n  <version file="1" date="%s"/>\n'
            '  <PLUGIN name=%s format="VST" category="Synth" manufacturer=%s\n'
            '          version="0.1.0.0" file=%s\n'
            '          uid="%08x" isInstrument="1" fileTime="0" infoUpdateTime="0"\n'
            '          numInputs="0" numOutputs="2" isShell="0"/>\n'
            '  <preset>%s</preset>\n  <state>%s</state>\n</pluginstate>\n'
            % (date, quoteattr(cfg["name"]), quoteattr(cfg["vendor"]), quoteattr(so), uid, escape(preset_name), b64enc(blob)))


def emit_values(presets):
    """presets.json converted the way the port kit converts it for the wrapper (gen_vst.preset_value), in file order."""
    import gen_vst  # noqa: E402  (the port kit, on sys.path above)
    d = json.load(open(os.path.join(HERE, "params.json")))
    params = {p["key"]: p for p in (d["params"] if isinstance(d, dict) else d)}
    out = []
    for n, pr in enumerate(presets):
        out.append("#%d\t%s" % (n, pr["name"]))
        for k, v in pr["values"].items():
            if k not in params:
                raise SystemExit("preset %r: %r is not a parameter" % (pr["name"], k))
            out.append("%s=%s" % (k, gen_vst.preset_value(params[k], v, "preset %r" % pr["name"])))
    sys.stdout.write("\n".join(out) + "\n")


def main():
    if sys.argv[1:] == ["--values"]:
        return emit_values(json.load(open(os.path.join(HERE, "presets.json")))["presets"])
    ap = argparse.ArgumentParser()
    ap.add_argument("states")
    ap.add_argument("out")
    ap.add_argument("--so", default=DEFAULT_SO)
    ap.add_argument("--only", default="")
    a = ap.parse_args()

    cfg = json.load(open(os.path.join(HERE, "vst.json")))
    presets = json.load(open(os.path.join(HERE, "presets.json")))["presets"]
    # The program count the plugin reports (the chunk set header carries it): 0 now that the presets are files, not
    # wrapper programs (a program list made MPC show one flat list instead of these category folders).
    cfg["nprograms"] = len(presets) if cfg.get("presets") else 0
    text = open(a.states).read()
    blocks = re.findall(r"^#(\d+)\t(.*?)\n(.*?)(?=^#\d+\t|\Z)", text, re.S | re.M)
    if len(blocks) != len(presets):
        raise SystemExit("%s has %d presets, presets.json %d: rebuild the states" % (a.states, len(blocks), len(presets)))
    only = {int(x) for x in a.only.split(",") if x}
    os.makedirs(a.out, exist_ok=True)
    for old in os.listdir(a.out):   # a fresh set each time: renamed or removed presets must not linger
        if old.endswith(".xpl"):
            os.remove(os.path.join(a.out, old))
    written = {}
    for idx, name, state in blocks:
        idx = int(idx)
        if only and idx not in only:
            continue
        p = presets[idx]
        if p["name"] != name:
            raise SystemExit("preset %d is %r in the states but %r in presets.json" % (idx, name, p["name"]))
        cat = p["category"]
        clean = "".join(c for c in name if c not in ILLEGAL and c != "-").strip()
        fn = "%04d-%s.xpl" % (idx, clean) if cat == "Init" else "%04d-%s-%s.xpl" % (idx, CATEGORY.get(cat, cat), clean)
        with open(os.path.join(a.out, fn), "w", encoding="utf-8") as f:
            f.write(xpl_text(cfg, a.so, name, state))
        written[cat] = written.get(cat, 0) + 1
    print("wrote %d presets to %s: %s" % (sum(written.values()), a.out,
                                          ", ".join("%s %d" % kv for kv in sorted(written.items()))))


if __name__ == "__main__":
    main()
